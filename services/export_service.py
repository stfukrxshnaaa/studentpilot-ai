"""
Export Service for StudyPilot AI.
Exports study plans, notes, flashcards, and quiz attempts to Markdown, HTML, CSV, and JSON.
"""

import json
import io
import pandas as pd
from typing import List, Dict, Any

def export_study_plan_markdown(plan: Dict[str, Any], items: List[Dict[str, Any]]) -> str:
    """Exports a study plan and its schedule items into formatted Markdown."""
    title = plan.get("title", "Study Plan")
    exam_date = plan.get("exam_date", "N/A")
    hours_per_day = plan.get("available_hours_per_day", 0)
    total_hours = plan.get("total_allocated_hours", 0)
    
    md = f"# 📅 {title}\n\n"
    md += f"- **Target Exam Date**: {exam_date}\n"
    md += f"- **Daily Study Target**: {hours_per_day} hours/day\n"
    md += f"- **Total Scheduled Hours**: {total_hours} hours\n\n"
    md += "## 🗓️ Scheduled Study Sessions\n\n"
    md += "| Day | Date | Activity Type | Session Title | Hours | Status |\n"
    md += "|---|---|---|---|---|---|\n"
    
    for item in items:
        status_icon = "✅ Done" if item.get("is_completed") else "⏳ Pending"
        day_num = item.get("day_number", 1)
        sched_date = item.get("scheduled_date", "")
        act_type = item.get("activity_type", "Study")
        s_title = item.get("session_title", "").replace("|", "-")
        hrs = item.get("allocated_hours", 0)
        md += f"| Day {day_num} | {sched_date} | {act_type} | {s_title} | {hrs} hrs | {status_icon} |\n"
        
    md += "\n---\n*Generated by StudyPilot AI - College Study Assistant*\n"
    return md

