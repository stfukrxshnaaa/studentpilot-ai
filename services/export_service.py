def export_study_plan_csv(items: List[Dict[str, Any]]) -> str:
    """Exports plan items as CSV string."""
    df = pd.DataFrame(items)
    cols = ["day_number", "scheduled_date", "activity_type", "session_title", "allocated_hours", "is_completed"]
    available_cols = [c for c in cols if c in df.columns]
    return df[available_cols].to_csv(index=False)

def export_note_markdown(note: Dict[str, Any]) -> str:
    """Formats a single note into clean Markdown with frontmatter."""
    title = note.get("title", "Untitled Note")
    content = note.get("content", "")
    tags = note.get("tags", "")
    created_at = note.get("created_at", "")
    subject = note.get("subject_name", "")
    topic = note.get("topic_title", "")
    
    md = f"# ✍️ {title}\n\n"
    if subject or topic:
        md += f"> **Subject:** {subject} &nbsp;|&nbsp; **Topic:** {topic}\n"
    if tags:
        md += f"> **Tags:** `{tags}`\n"
    if created_at:
        md += f"> **Created:** {created_at}\n\n"
    md += "---\n\n"
    md += content
    md += "\n\n---\n*Exported from StudyPilot AI*\n"
    return md

def export_notes_json(notes: List[Dict[str, Any]]) -> str:
    """Exports list of notes to formatted JSON."""
    return json.dumps(notes, indent=2, default=str)

def export_flashcards_csv(flashcards: List[Dict[str, Any]]) -> str:
    """Exports flashcards to Anki-compatible CSV."""
    df = pd.DataFrame(flashcards)
    cols = ["question", "answer", "difficulty_rating", "review_count", "subject_name", "topic_title"]
    avail = [c for c in cols if c in df.columns]
    return df[avail].to_csv(index=False)
